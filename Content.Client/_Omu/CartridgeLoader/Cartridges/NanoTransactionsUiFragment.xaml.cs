using Content.Client._DV.CartridgeLoader.Cartridges;
using Content.Shared._DV.CartridgeLoader.Cartridges;
using Content.Shared._Omu.CartridgeLoader.Cartridges;
using Content.Shared.Atmos.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Omu.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class NanoTransactionsUiFragment : BoxContainer
{
    public event Action<EntityUid?, EntityUid?, int?>? OnMoneySent;
    public event Action<EntityUid?, EntityUid?, int?>? OnMoneyReceived;
    public bool moneySendOptionToggled = false;
    public bool moneyRequestOptionToggled = false;
    private MetaDataComponent? selfMeta = null;

    public NanoTransactionsUiFragment()
    {
        RobustXamlLoader.Load(this);
        SetupEventHandlers();
    }

    private void SetupEventHandlers()
    {
        MoneySendOption.OnToggled += _ => ToggleSend();
        MoneyRequestOption.OnToggled += _ => ToggleRequest();

        ConfirmButton.OnPressed += _ => ProcessConfirm();
    }

    private void ToggleSend()
    {
        moneySendOptionToggled = !moneySendOptionToggled;
        moneyRequestOptionToggled = false;
        MoneyRequestOption.Pressed = false;
    }

    private void ToggleRequest()
    {
        moneyRequestOptionToggled = !moneyRequestOptionToggled;
        moneySendOptionToggled = false;
        MoneySendOption.Pressed = false;
    }

    private void ProcessConfirm()
    {
        if (moneySendOptionToggled)
        {
            var receiver = ReceiverInput.Text;
            var amountText = AmountEdit.Text;
            if (int.TryParse(amountText, out int amount))
            {
                OnMoneySent?.Invoke(selfMeta, receiver, amount);
            }
        }
    }

    public void UpdateState(NanoTransactionsUiState state)
    {
        // Update the UI based on the state
        UpdateTransactionList(state.History);
        UpdatePlayerList(state.Players);
        UpdateBalance(state.Balance);
        selfMeta = state.Self;
    }

    public void UpdateTransactionList(List<NanoTransaction> history)
    {
        HistoryList.RemoveAllChildren();
        foreach (var transaction in history)
        {
            var playerLabel = new Label
            {
                Text = $"Sender: {transaction._sender}, Receiver: {transaction._receiver}, Amount: {transaction._amount}"
            };
            HistoryList.AddChild(playerLabel);
        }
    }

    public void UpdatePlayerList(List<MetaDataComponent> players)
    {
        PlayerList.RemoveAllChildren();
        foreach (var player in players)
        {
            var playerLabel = new Label
            {
                Text = $"{player.EntityName}"
            };
            PlayerList.AddChild(playerLabel);
        }
    }

    public void UpdateBalance(int balance)
    {
        Balance.Text = Loc.GetString("nano-transactions-balance", ("balance", balance));
    }
}
